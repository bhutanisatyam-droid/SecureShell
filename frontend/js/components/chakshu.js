// CallShield Chakshu / Sanchar Saathi Reporting Workflow
// Facilitates guided reporting to the Department of Telecommunications (DoT) Chakshu facility
// and National Cybercrime Reporting Portal (cybercrime.gov.in / 1930).

import { esc, fmtDateTime, CHAKSHU_CATEGORY_MAP, CATEGORY_DESCRIPTIONS, redactSensitiveText, extractKeptIdentifiers } from '../formatters.js';

export class ChakshuWorkflow {
  constructor(containerId) {
    this.container = document.getElementById(containerId);
    this.sessionData = null;
    this.currentStep = 1;
    this.selectedEvidenceIds = new Set();
    this.redactPii = true;
    this.customSummary = '';
    this.suspectedIdentifier = '';
    this.keptIdentifiers = [];
    this.submissionStatus = 'draft'; // 'draft' | 'prepared' | 'portal_opened' | 'confirmed'
    this.govReferenceId = '';
  }

  open(sessionData) {
    this.sessionData = sessionData;
    this.currentStep = 1;
    this.submissionStatus = localStorage.getItem(`cs_chakshu_${sessionData.sessionId}`) || 'draft';
    this.govReferenceId = localStorage.getItem(`cs_chakshu_ref_${sessionData.sessionId}`) || '';

    // Initialize selected evidence: select all non-retracted evidence by default
    this.selectedEvidenceIds = new Set();
    const retractions = sessionData.retractions || new Map();
    const evidenceEvents = (sessionData.events || []).filter(e => e.event_type === 'evidence');
    for (const ev of evidenceEvents) {
      if (!retractions.has(ev.payload.evidence_id)) {
        this.selectedEvidenceIds.add(ev.payload.evidence_id);
      }
    }

    // Try extracting suspected identifier from chat or transcript
    this.suspectedIdentifier = this._findSuspectedIdentifier(sessionData);
    this._generateDefaultSummary();

    this.render();
    this.container.classList.remove('hidden');
    document.body.classList.add('modal-open');
  }

  close() {
    this.container.classList.add('hidden');
    document.body.classList.remove('modal-open');
  }

  _findSuspectedIdentifier(sessionData) {
    // Look for remote caller details, chat sender labels, or links in chat messages
    const chatEvents = (sessionData.events || []).filter(e => e.event_type === 'chat_message');
    for (const c of chatEvents) {
      if (c.payload.links && c.payload.links.length > 0) {
        return c.payload.links[0];
      }
      if (c.payload.sender_label) {
        return c.payload.sender_label;
      }
    }
    // Default placeholder for Meet call
    return `Google Meet Call (Session: ${sessionData.sessionId})`;
  }

  _isLocalEvidence(ev) {
    if (!ev || !ev.payload) return false;
    if (ev.payload.source_modality === 'video') return false;
    const srcIds = new Set(ev.payload.source_event_ids || []);
    const allEvents = this.sessionData?.events || [];
    for (const e of allEvents) {
      if (srcIds.has(e.event_id)) {
        const p = e.payload || {};
        if (p.speaker_role === 'local' || p.sender_role === 'local') {
          return true;
        }
      }
    }
    return false;
  }

  _generateDefaultSummary() {
    if (!this.sessionData) return;
    const peak = this.sessionData.peakAssessment || {};
    const evidenceEvents = (this.sessionData.events || [])
      .filter(e => e.event_type === 'evidence' && this.selectedEvidenceIds.has(e.payload.evidence_id));

    const categories = Array.from(new Set(evidenceEvents.map(e => e.payload.category)));
    const catTitles = categories.map(c => CATEGORY_DESCRIPTIONS[c] || c).join('; ');

    const keptSet = new Set();
    const quotes = evidenceEvents.map(e => {
      const isLocal = this._isLocalEvidence(e);
      let text = e.payload.quoted_text_or_observation || '';
      if (this.redactPii) {
        text = redactSensitiveText(text, isLocal);
      }
      if (!isLocal) {
        extractKeptIdentifiers(text).forEach(id => keptSet.add(id));
      }
      return `• [${e.payload.source_modality.toUpperCase()}${isLocal ? ' (LOCAL VICTIM)' : ''}] "${text}"`;
    }).join('\n');

    this.keptIdentifiers = Array.from(keptSet);

    let text = `CallShield Threat Report for Suspicious Communication:
Medium: Google Meet Video Call
Suspected Handle / Link: ${this.suspectedIdentifier}
Peak Heuristic Risk: ${peak.risk_level ? peak.risk_level.toUpperCase() : 'HIGH'} (${peak.risk_index ?? '–'}/100)
Observed Threat Patterns: ${catTitles || 'Impersonation / Coercive Fraud'}

Key Recorded Evidence:
${quotes || 'Suspicious demands for money / digital arrest / legal threats recorded during call.'}

Timestamp of incident: ${fmtDateTime(this.sessionData.createdMs || Date.now())}
Generated by CallShield AI monitoring client.`;

    this.customSummary = text;
  }

  _getChakshuCategory() {
    const evidenceEvents = (this.sessionData.events || [])
      .filter(e => e.event_type === 'evidence' && this.selectedEvidenceIds.has(e.payload.evidence_id));
    for (const ev of evidenceEvents) {
      const mapped = CHAKSHU_CATEGORY_MAP[ev.payload.category];
      if (mapped) return mapped;
    }
    return 'Impersonation as Police, CBI, Customs, Aadhaar, RBI etc.';
  }

  render() {
    if (!this.sessionData) return;

    const chakshuCat = this._getChakshuCategory();
    const evidenceEvents = (this.sessionData.events || []).filter(e => e.event_type === 'evidence');
    const retractions = this.sessionData.retractions || new Map();

    const statusBadge = {
      draft: '<span class="status-pill status-draft"><span class="dot"></span> 1. Draft Incident Review</span>',
      prepared: '<span class="status-pill status-prepared"><span class="dot"></span> 2. Report Redacted & Ready</span>',
      portal_opened: '<span class="status-pill status-opened"><span class="dot"></span> 3. Official Portal Opened</span>',
      confirmed: '<span class="status-pill status-confirmed"><span class="dot"></span> 4. User Confirmed Filed</span>',
    }[this.submissionStatus] || '';

    this.container.innerHTML = `
      <div class="modal-backdrop" id="chakshuBackdrop"></div>
      <div class="modal-card modal-large" role="dialog" aria-modal="true" aria-labelledby="chakshuTitle">
        <div class="modal-header">
          <div>
            <div class="modal-pretitle">Official Sanchar Saathi Reporting Facility</div>
            <h2 id="chakshuTitle" class="modal-title">Report Suspicious Communication (Chakshu)</h2>
          </div>
          <div class="modal-header-actions">
            ${statusBadge}
            <button class="icon-button" id="chakshuCloseBtn" title="Close modal" aria-label="Close">✕</button>
          </div>
        </div>

        <div class="chakshu-stepper">
          <div class="step-item ${this.currentStep === 1 ? 'active' : ''} ${this.currentStep > 1 ? 'completed' : ''}" data-step="1">
            <span class="step-num">1</span> Review Evidence
          </div>
          <div class="step-arrow">→</div>
          <div class="step-item ${this.currentStep === 2 ? 'active' : ''} ${this.currentStep > 2 ? 'completed' : ''}" data-step="2">
            <span class="step-num">2</span> Redact &amp; Summarize
          </div>
          <div class="step-arrow">→</div>
          <div class="step-item ${this.currentStep === 3 ? 'active' : ''}" data-step="3">
            <span class="step-num">3</span> Official Portal Handoff
          </div>
        </div>

        <div class="modal-body">
          ${this._renderStepContent(chakshuCat, evidenceEvents, retractions)}
        </div>

        <div class="modal-footer">
          <div class="footer-left">
            <span class="legal-disclaimer">
              <b>Mandatory Notice:</b> CallShield provides an assistive review &amp; export workflow. Under Government of India policy, final submission requires citizen OTP verification on <a href="https://sancharsaathi.gov.in" target="_blank" rel="noopener">sancharsaathi.gov.in</a>. CallShield does NOT auto-submit without user action.
            </span>
          </div>
          <div class="footer-right">
            ${this.currentStep > 1 ? `<button class="btn btn-ghost" id="chakshuPrevBtn">Back</button>` : ''}
            ${this.currentStep < 3 
              ? `<button class="btn btn-primary" id="chakshuNextBtn">Continue to Step ${this.currentStep + 1}</button>` 
              : `<button class="btn btn-ghost" id="chakshuDoneBtn">Close</button>`}
          </div>
        </div>
      </div>
    `;

    this._bindEvents();
  }

  _renderStepContent(chakshuCat, evidenceEvents, retractions) {
    if (this.currentStep === 1) {
      return `
        <div class="step-pane">
          <div class="alert-box info-box">
            <div class="alert-icon">ℹ</div>
            <div>
              <b>Select Incident Evidence for Official Filing:</b>
              CallShield detected high-risk fraud signals during this Google Meet session. Verify which items to include in the complaint package. Retracted statements (e.g. jokes or educational quotes) are excluded by default.
            </div>
          </div>

          <div class="form-row grid-2">
            <div class="form-group">
              <label class="form-label">Communication Medium</label>
              <div class="field-static">Google Meet (Desktop Chrome Web Call)</div>
              <p class="field-help">Chakshu supports Call/SMS/WhatsApp. Web calls are reported under "Any Other Suspected Fraud" or via cybercrime.gov.in.</p>
            </div>
            <div class="form-group">
              <label class="form-label">Suspected Caller Handle / Link</label>
              <input type="text" class="input-text" id="suspectedIdentifierInput" value="${esc(this.suspectedIdentifier)}" placeholder="e.g. Meet URL or Caller Name" />
              <p class="field-help">Identifier of the scammer or meeting room.</p>
            </div>
          </div>

          <div class="identifiers-kept-panel">
            <div class="identifiers-kept-header">
              <span class="font-semibold text-sm">Identifiers Kept for the Report (Scammer Details):</span>
              <span class="text-muted text-xs">Victim personal data is auto-redacted; scammer numbers/handles are retained to assist authorities.</span>
            </div>
            <div class="identifiers-kept-list" id="keptIdentifiersList">
              ${(this.keptIdentifiers && this.keptIdentifiers.length > 0)
                ? this.keptIdentifiers.map(id => `
                    <span class="kept-chip" data-id="${esc(id)}">
                      ${esc(id)}
                      <button type="button" class="btn-remove-kept" data-id="${esc(id)}" title="Click to manually remove/redact from report">✕</button>
                    </span>
                  `).join('')
                : '<span class="text-muted text-xs">No specific scammer phone numbers, accounts or UPI handles detected in remote evidence.</span>'}
            </div>
          </div>

          <div class="section-title-bar">
            <h4>Observed Fraud Signals &amp; Evidence Ledger (${evidenceEvents.length} items)</h4>
            <div class="table-actions">
              <button class="btn-link" id="selectAllEvidence">Select All</button>
              <span class="sep">|</span>
              <button class="btn-link" id="deselectAllEvidence">Deselect All</button>
            </div>
          </div>

          <div class="evidence-checklist">
            ${evidenceEvents.length === 0 ? '<p class="muted p-4">No fraud evidence items recorded for this session.</p>' : ''}
            ${evidenceEvents.map(e => {
              const p = e.payload;
              const isRetracted = retractions.has(p.evidence_id);
              const isChecked = this.selectedEvidenceIds.has(p.evidence_id);
              return `
                <label class="evidence-check-item ${isRetracted ? 'is-retracted' : ''}">
                  <input type="checkbox" class="ev-cb" data-id="${esc(p.evidence_id)}" ${isChecked ? 'checked' : ''} ${isRetracted ? 'disabled' : ''} />
                  <div class="ev-content">
                    <div class="ev-header">
                      <span class="badge ${isRetracted ? 'badge-muted' : 'badge-danger'}">${esc(p.category)}</span>
                      <span class="tag">${esc(p.source_modality)}</span>
                      <span class="time">${fmtDateTime(p.t_end_ms)}</span>
                      ${isRetracted ? `<span class="badge badge-warn">RETRACTED: ${esc(retractions.get(p.evidence_id))}</span>` : ''}
                      ${p.quality != null ? `<span class="quality-label">quality=${p.quality}</span>` : ''}
                    </div>
                    <div class="ev-quote">“${esc(p.quoted_text_or_observation)}”</div>
                    <div class="ev-category-desc">${esc(CATEGORY_DESCRIPTIONS[p.category] || '')}</div>
                  </div>
                </label>
              `;
            }).join('')}
          </div>
        </div>
      `;
    }

    if (this.currentStep === 2) {
      return `
        <div class="step-pane">
          <div class="alert-box security-box">
            <div class="alert-icon">🛡</div>
            <div>
              <b>PII Redaction &amp; Incident Summary:</b>
              Before copying details to the government portal, review the generated complaint text. CallShield automatically redacts victim personal phone numbers, Aadhaar numbers, and financial OTPs to preserve privacy.
            </div>
          </div>

          <div class="redaction-toolbar">
            <label class="toggle-control">
              <input type="checkbox" id="piiRedactionToggle" ${this.redactPii ? 'checked' : ''} />
              <span class="toggle-slider"></span>
              <span class="toggle-label"><b>Auto-Redact Personal Information</b> (Phone, Card, Aadhaar, OTP)</span>
            </label>
            <button class="btn btn-sm btn-ghost" id="regenerateSummaryBtn">Regenerate from Evidence</button>
          </div>

          <div class="form-group">
            <label class="form-label" for="chakshuSummaryText">Editable Incident Description for Official Portal</label>
            <textarea id="chakshuSummaryText" class="textarea-field" rows="12">${esc(this.customSummary)}</textarea>
            <div class="field-meta">
              <span>Word count: ${this.customSummary.trim().split(/\s+/).filter(Boolean).length} words</span>
              <span>Characters: ${this.customSummary.length}</span>
            </div>
          </div>

          <div class="mapped-category-summary">
            <span class="label">Mapped Official Chakshu Category:</span>
            <span class="value"><b>${esc(chakshuCat)}</b></span>
          </div>
        </div>
      `;
    }

    if (this.currentStep === 3) {
      return `
        <div class="step-pane">
          <div class="alert-box success-box">
            <div class="alert-icon">✓</div>
            <div>
              <b>Report Package Ready for Official Portal Submission:</b>
              Copy the standardized fields below into the official Department of Telecommunications Sanchar Saathi Chakshu form or the National Cybercrime Portal.
            </div>
          </div>

          <div class="copy-field-grid">
            <div class="copy-card">
              <div class="copy-card-head">
                <span class="card-label">1. Suspected Fraud Category</span>
                <button class="btn-copy" data-copy="${esc(chakshuCat)}">Copy</button>
              </div>
              <div class="copy-val">${esc(chakshuCat)}</div>
            </div>

            <div class="copy-card">
              <div class="copy-card-head">
                <span class="card-label">2. Medium of Communication</span>
                <button class="btn-copy" data-copy="Google Meet Video Call / Web">Copy</button>
              </div>
              <div class="copy-val">Google Meet Video Call / Web</div>
            </div>

            <div class="copy-card">
              <div class="copy-card-head">
                <span class="card-label">3. Suspected Number / Link / Handle</span>
                <button class="btn-copy" data-copy="${esc(this.suspectedIdentifier)}">Copy</button>
              </div>
              <div class="copy-val">${esc(this.suspectedIdentifier)}</div>
            </div>

            <div class="copy-card">
              <div class="copy-card-head">
                <span class="card-label">4. Date and Time of Incident</span>
                <button class="btn-copy" data-copy="${fmtDateTime(this.sessionData.createdMs || Date.now())}">Copy</button>
              </div>
              <div class="copy-val">${fmtDateTime(this.sessionData.createdMs || Date.now())}</div>
            </div>
          </div>

          <div class="copy-card copy-card-full">
            <div class="copy-card-head">
              <span class="card-label">5. Full Redacted Complaint Description</span>
              <button class="btn-copy btn-primary-sm" data-copy="${esc(this.customSummary)}">Copy Full Description</button>
            </div>
            <pre class="copy-code-block">${esc(this.customSummary)}</pre>
          </div>

          <div class="portal-handoff-banner">
            <div class="banner-body">
              <h4>Proceed to Official Government Channels</h4>
              <p>Click below to open the official Sanchar Saathi Chakshu portal in a new tab. Paste the copied details and complete OTP verification.</p>
              <div class="portal-links">
                <a href="https://sancharsaathi.gov.in/sfc/" target="_blank" rel="noopener noreferrer" class="btn btn-primary" id="openChakshuPortalBtn">
                  Open Chakshu Portal (sancharsaathi.gov.in) ↗
                </a>
                <a href="https://cybercrime.gov.in" target="_blank" rel="noopener noreferrer" class="btn btn-secondary" id="openCybercrimePortalBtn">
                  National Cybercrime Portal (cybercrime.gov.in) ↗
                </a>
                <div class="helpline-pill">
                  <b>Helpline:</b> Dial <b>1930</b> for Immediate Financial Fraud Freeze
                </div>
              </div>
            </div>
          </div>

          <div class="confirmation-section">
            <h4>Record Submission Status</h4>
            <p class="field-help">Once you submit the report on the portal, mark it confirmed here to record the filing in CallShield session history.</p>
            <div class="form-row">
              <input type="text" class="input-text" id="govRefInput" value="${esc(this.govReferenceId)}" placeholder="Enter Portal Complaint / Acknowledgment Number (e.g. SFC-2026-XXXXX)" />
              <button class="btn ${this.submissionStatus === 'confirmed' ? 'btn-success' : 'btn-outline'}" id="confirmSubmissionBtn">
                ${this.submissionStatus === 'confirmed' ? '✓ Submission Confirmed' : 'Confirm Submission'}
              </button>
            </div>
            ${this.submissionStatus === 'confirmed' ? `
              <div class="status-confirmed-msg">
                ✓ Recorded as confirmed by user. Reference: <b>${esc(this.govReferenceId || 'Not specified')}</b>
              </div>
            ` : ''}
          </div>
        </div>
      `;
    }

    return '';
  }

  _bindEvents() {
    const backdrop = document.getElementById('chakshuBackdrop');
    const closeBtn = document.getElementById('chakshuCloseBtn');
    const doneBtn = document.getElementById('chakshuDoneBtn');
    const prevBtn = document.getElementById('chakshuPrevBtn');
    const nextBtn = document.getElementById('chakshuNextBtn');

    if (backdrop) backdrop.onclick = () => this.close();
    if (closeBtn) closeBtn.onclick = () => this.close();
    if (doneBtn) doneBtn.onclick = () => this.close();

    if (prevBtn) {
      prevBtn.onclick = () => {
        if (this.currentStep > 1) {
          this.currentStep--;
          this.render();
        }
      };
    }

    if (nextBtn) {
      nextBtn.onclick = () => {
        if (this.currentStep === 1) {
          const idInput = document.getElementById('suspectedIdentifierInput');
          if (idInput) this.suspectedIdentifier = idInput.value.trim();
          this._generateDefaultSummary();
          this.submissionStatus = 'prepared';
          this._persistStatus();
          this.currentStep = 2;
          this.render();
        } else if (this.currentStep === 2) {
          const summaryInput = document.getElementById('chakshuSummaryText');
          if (summaryInput) this.customSummary = summaryInput.value;
          this.currentStep = 3;
          this.render();
        }
      };
    }

    // Step 1 Checkbox listeners
    const checkboxes = this.container.querySelectorAll('.ev-cb');
    checkboxes.forEach(cb => {
      cb.onchange = (e) => {
        const id = e.target.dataset.id;
        if (e.target.checked) {
          this.selectedEvidenceIds.add(id);
        } else {
          this.selectedEvidenceIds.delete(id);
        }
        this._generateDefaultSummary();
        this.render();
      };
    });

    const selectAllBtn = document.getElementById('selectAllEvidence');
    if (selectAllBtn) {
      selectAllBtn.onclick = () => {
        const retractions = this.sessionData.retractions || new Map();
        for (const ev of (this.sessionData.events || [])) {
          if (ev.event_type === 'evidence' && !retractions.has(ev.payload.evidence_id)) {
            this.selectedEvidenceIds.add(ev.payload.evidence_id);
          }
        }
        this._generateDefaultSummary();
        this.render();
      };
    }

    const deselectAllBtn = document.getElementById('deselectAllEvidence');
    if (deselectAllBtn) {
      deselectAllBtn.onclick = () => {
        this.selectedEvidenceIds.clear();
        this._generateDefaultSummary();
        this.render();
      };
    }

    // Step 1 Kept Identifiers removal
    const removeKeptBtns = this.container.querySelectorAll('.btn-remove-kept');
    removeKeptBtns.forEach(btn => {
      btn.onclick = (e) => {
        e.preventDefault();
        e.stopPropagation();
        const targetId = btn.dataset.id;
        if (!targetId) return;
        this.keptIdentifiers = (this.keptIdentifiers || []).filter(x => x !== targetId);
        if (this.customSummary) {
          const escTarget = targetId.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
          this.customSummary = this.customSummary.replace(new RegExp(escTarget, 'g'), '[REDACTED_BY_USER]');
        }
        this.render();
      };
    });

    // Step 2 Redaction listeners
    const redactionToggle = document.getElementById('piiRedactionToggle');
    if (redactionToggle) {
      redactionToggle.onchange = (e) => {
        this.redactPii = e.target.checked;
        this._generateDefaultSummary();
        const summaryArea = document.getElementById('chakshuSummaryText');
        if (summaryArea) summaryArea.value = this.customSummary;
      };
    }

    const regenBtn = document.getElementById('regenerateSummaryBtn');
    if (regenBtn) {
      regenBtn.onclick = () => {
        this._generateDefaultSummary();
        const summaryArea = document.getElementById('chakshuSummaryText');
        if (summaryArea) summaryArea.value = this.customSummary;
      };
    }

    // Step 3 Copy Buttons
    const copyBtns = this.container.querySelectorAll('.btn-copy');
    copyBtns.forEach(btn => {
      btn.onclick = async () => {
        const text = btn.dataset.copy;
        try {
          await navigator.clipboard.writeText(text);
          const orig = btn.textContent;
          btn.textContent = 'Copied!';
          btn.classList.add('copied');
          setTimeout(() => {
            btn.textContent = orig;
            btn.classList.remove('copied');
          }, 2000);
        } catch (err) {
          console.warn('Clipboard write failed:', err);
        }
      };
    });

    // Portal link click tracker
    const openPortalBtn = document.getElementById('openChakshuPortalBtn');
    if (openPortalBtn) {
      openPortalBtn.onclick = () => {
        if (this.submissionStatus !== 'confirmed') {
          this.submissionStatus = 'portal_opened';
          this._persistStatus();
          this.render();
        }
      };
    }

    // Confirmation button
    const confirmBtn = document.getElementById('confirmSubmissionBtn');
    if (confirmBtn) {
      confirmBtn.onclick = () => {
        const refInput = document.getElementById('govRefInput');
        this.govReferenceId = refInput ? refInput.value.trim() : '';
        this.submissionStatus = 'confirmed';
        this._persistStatus();
        this.render();
      };
    }
  }

  _persistStatus() {
    if (!this.sessionData) return;
    try {
      localStorage.setItem(`cs_chakshu_${this.sessionData.sessionId}`, this.submissionStatus);
      if (this.govReferenceId) {
        localStorage.setItem(`cs_chakshu_ref_${this.sessionData.sessionId}`, this.govReferenceId);
      }
    } catch {}
  }
}

