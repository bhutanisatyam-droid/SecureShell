"""Incident report built from the stored event ledger. Never claims an official complaint was filed."""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any

from .contracts import LEVEL_ORDER

REPORTING_GUIDANCE = [
    "Call the National Cybercrime Helpline: 1930",
    "File a complaint at https://cybercrime.gov.in",
    "Report the number/handle via Chakshu on the Sanchar Saathi app",
]
DISCLAIMER = ("Generated by the CallShield proof of concept. NOT submitted to any authority. "
              "Bank actions shown are SIMULATED. Risk index is a heuristic score, not a probability.")


def _ts(ms: int | None) -> str | None:
    if ms is None:
        return None
    return datetime.fromtimestamp(ms / 1000, tz=timezone.utc).isoformat()


def build_report(session_id: str, events: list[dict], health: dict | None,
                 transfers: list[dict]) -> dict[str, Any]:
    by_type: dict[str, list[dict]] = {}
    for e in events:
        by_type.setdefault(e["event_type"], []).append(e)
    assessments = [e["payload"] for e in by_type.get("assessment", [])]
    peak = max(assessments, key=lambda a: (LEVEL_ORDER[a["risk_level"]], a["risk_index"]), default=None)
    retracted = {i: e["payload"]["reason"] for e in by_type.get("retraction", []) for i in e["payload"]["evidence_ids"]}
    evidence = [e["payload"] for e in by_type.get("evidence", [])]
    actions = [e["payload"] | {"source": e["source"], "time": _ts(e["timestamp_ms"])}
               for e in by_type.get("action", [])]
    return {
        "session_id": session_id,
        "generated_at": _ts(max(e["timestamp_ms"] for e in events)),
        "started_at": _ts(events[0]["timestamp_ms"]),
        "peak_assessment": peak,
        "final_assessment": assessments[-1] if assessments else None,
        "inference_modes_seen": sorted({a["inference_mode"] for a in assessments}),
        "evidence": [
            {"category": ev["category"], "quote": ev["quoted_text_or_observation"],
             "modality": ev["source_modality"], "rules": ev["rule_refs"],
             "time": _ts(ev["t_end_ms"]), "mock": ev.get("is_mock", False),
             "retracted": retracted.get(ev["evidence_id"])}
            for ev in evidence
        ],
        "actions": actions,
        "transfers": transfers,
        "monitoring": health,
        "reporting_guidance": REPORTING_GUIDANCE,
        "official_complaint_submitted": False,
        "disclaimer": DISCLAIMER,
    }


def report_markdown(r: dict[str, Any]) -> str:
    peak = r["peak_assessment"] or {}
    lines = [
        f"# CallShield incident report: {r['session_id']}",
        "",
        f"> {r['disclaimer']}",
        "",
        f"- Started: {r['started_at']}",
        f"- Peak risk: **{peak.get('risk_level', 'n/a')}** ({peak.get('risk_index', 'n/a')}/100), "
        f"evidence strength {peak.get('evidence_strength', 'n/a')}",
        f"- Patterns: {', '.join(peak.get('patterns', [])) or 'none'}",
        f"- Inference: {', '.join(r['inference_modes_seen']) or 'none'}",
        "",
        "## Evidence",
    ]
    for ev in r["evidence"]:
        mock = " (MOCK)" if ev["mock"] else ""
        rules = f" [{', '.join(ev['rules'])}]" if ev["rules"] else ""
        rt = f" (RETRACTED: {ev['retracted']})" if ev["retracted"] else ""
        lines.append(f"- {ev['time']} {ev['category']}{rules} via {ev['modality']}{mock}: “{ev['quote']}”{rt}")
    lines += ["", "## Actions"]
    for a in r["actions"]:
        lines.append(f"- {a['time']} {a['action_type']} -> {a['status']} ({a['source']})")
    lines += ["", "## Simulated bank transfers"]
    for t in r["transfers"]:
        lines.append(f"- {t['transfer_id']} INR {t['amount']:.2f} to {t['payee']}: {t['status']} ({t['reason']})")
    lines += ["", "## What to do next"] + [f"- {g}" for g in r["reporting_guidance"]]
    return "\n".join(lines) + "\n"
